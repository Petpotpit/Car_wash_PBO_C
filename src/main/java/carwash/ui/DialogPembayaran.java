    public void setTotal(double total) {
        this.total = total;
        lblTotal.setText("Total: " + Rupiah.format(total));
        hitungKembalian();
    }

    /** null jika dibatalkan. */
    public Long getUang() { return uang; }

    private void hitungKembalian() {
        try {
            long u = Validator.validasiUang(txtUang.getText());
            lblKembalian.setText(u >= total
                    ? "Kembalian: " + Rupiah.format(u - total)
                    : "Uang kurang " + Rupiah.format(total - u));
        } catch (InputTidakValidException e) {
            lblKembalian.setText("Kembalian: -");
        }
    }

