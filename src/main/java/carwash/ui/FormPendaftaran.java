    private void btnDaftarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDaftarActionPerformed
               try {
            Customer c = customerService.daftar(
                    txtNama.getText(), txtTelepon.getText(), Session.getUser());
            JOptionPane.showMessageDialog(this,
                    "Pelanggan terdaftar:\n" + c.getId() + " - " + c.getNama(),
                    "Berhasil", JOptionPane.INFORMATION_MESSAGE);
            txtNama.setText("");
            txtTelepon.setText("");
            txtNama.requestFocus();
        } catch (InputTidakValidException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(),
                    "Input tidak valid", JOptionPane.WARNING_MESSAGE);
        } catch (AksesDitolakException | PenyimpananGagalException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(),
                    "Gagal", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDaftarActionPerformed

