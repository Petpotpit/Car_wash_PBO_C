    private void refreshList() {
        DefaultListModel<String> model = new DefaultListModel<>();
        for (LocalDate t : kalender.getDaftarUrut()) {
            model.addElement(t.toString());
        }
        lstTanggal.setModel(model);
    }

    /** Tulis ke file. Jika gagal, kembalikan nilai lama (rollback). */
    private boolean simpanAtauRollback(Set<LocalDate> nilaiLama) {
        try {
            repo.simpanTanggalMerah(kalender.getDaftarUrut());
            return true;
        } catch (IOException e) {
            kalender.gantiSemua(nilaiLama);
            JOptionPane.showMessageDialog(this,
                    "Gagal menyimpan, perubahan dibatalkan: " + e.getMessage(),
                    "Penyimpanan gagal", JOptionPane.ERROR_MESSAGE);
            return false;
        }
    }

