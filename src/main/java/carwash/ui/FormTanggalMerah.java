    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        LocalDate t;
        try {
            t = LocalDate.parse(txtTanggal.getText().trim());
        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Format tanggal harus yyyy-MM-dd, contoh 2026-12-25",
                    "Input tidak valid", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Set<LocalDate> lama = kalender.salinan();          // 1. simpan nilai lama
        try {
            kalender.tambahTanggal(t, Session.getUser());  // 2. ubah di memori
            if (simpanAtauRollback(lama)) {                // 3. tulis file, 4. rollback jika gagal
                txtTanggal.setText("");
            }
        } catch (InputTidakValidException | AksesDitolakException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(),
                    "Tidak dapat menambah", JOptionPane.WARNING_MESSAGE);
        }
        refreshList();
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        String dipilih = lstTanggal.getSelectedValue();
        if (dipilih == null) {
            JOptionPane.showMessageDialog(this, "Pilih tanggal di daftar terlebih dahulu",
                    "Belum memilih", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        Set<LocalDate> lama = kalender.salinan();
        try {
            kalender.hapusTanggal(LocalDate.parse(dipilih), Session.getUser());
            simpanAtauRollback(lama);
        } catch (InputTidakValidException | AksesDitolakException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(),
                    "Tidak dapat menghapus", JOptionPane.WARNING_MESSAGE);
        }
        refreshList();
    }//GEN-LAST:event_btnHapusActionPerformed

