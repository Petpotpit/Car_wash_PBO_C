    private void tampilStatusHari() {
        LocalDate hari = LocalDate.now();
        boolean aktif = ctx.getKalender().isProgramAktif(hari);
        String tgl = DateTimeFormatter.ofPattern("EEEE, d MMMM yyyy",
                Locale.forLanguageTag("id-ID")).format(hari);

        lblStatusHari.setText("Hari ini: " + tgl + " - " + (aktif
                ? "Program loyalitas aktif"
                : "Program loyalitas tidak aktif hari ini (Minggu/tanggal merah)"));

        boolean kosong = !ctx.getKalender().adaTanggalUntukTahun(hari.getYear());
        lblInfoKalender.setText(kosong
                ? "Daftar tanggal merah tahun ini belum diisi, hubungi manager" : " ");
    }

    private void tampilPelanggan() {
        if (terpilih == null) {
            lblPelanggan.setText("Belum ada pelanggan dipilih");
            lblHitungan.setText(" ");
            lblBadge.setText(" ");
            return;
        }
        String id = terpilih.getId();
        int h = ctx.getLoyalty().getHitungan(id);
        lblPelanggan.setText(terpilih.getNama() + " (" + id + ") - " + terpilih.getTelepon());
        lblHitungan.setText("Cuci berbayar: " + h + "/" + LoyaltyTracker.TARGET);
        lblBadge.setText(ctx.getLoyalty().rewardSiap(id, LocalDate.now())
                ? "Reward siap dipakai" : " ");
    }


